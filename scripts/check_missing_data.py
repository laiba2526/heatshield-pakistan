"""Member 1 - missing-data report for every Bronze file.

Checks each raw file (Open-Meteo archive and forecasts, ERA5, NASA POWER):
Quality Gate 1 result, period, hourly timestamp gaps and duplicates, missing
values and physical-range violations per variable, NASA POWER -999 fill
values and value ranges. Writes ``data/missing_data_report.txt`` (Markdown).

Usage: ``python scripts/check_missing_data.py`` (part of ``make -C src reports``)
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from heatshield import bronze, config  # noqa: E402
from heatshield.bronze import NASA_FILL_VALUE  # noqa: E402

VARS = config.VARIABLES
REPORT = config.DATA / "missing_data_report.txt"


def bronze_inspection() -> tuple[str, list[dict]]:
    manifest = bronze.load_manifest()
    rows = []
    for bf in bronze.discover(max_forecasts_per_city=10_000):
        raw_fill = 0
        if bf.source == "nasa_power":
            params = json.loads(bf.path.read_text(encoding="utf-8"))["properties"]["parameter"]
            raw_fill = sum(1 for v in params.values() for x in v.values() if x == NASA_FILL_VALUE)
        bronze.read_and_gate(bf, manifest)
        r = {"file": bf.path.name, "source": bf.source, "city": bf.city, "gate1": "pass" if bf.passed else "FAIL",
             "fill_values_-999": raw_fill}
        if bf.frame is not None:
            df = bf.frame.sort_values("timestamp_utc")
            ts = df["timestamp_utc"]
            expected = int((ts.max() - ts.min()) / pd.Timedelta(hours=1)) + 1
            r.update({"first_utc": ts.min().strftime("%Y-%m-%d %H:%M"), "last_utc": ts.max().strftime("%Y-%m-%d %H:%M"),
                      "timestamps": len(df), "missing_hours_in_range": expected - ts.nunique(),
                      "duplicate_timestamps": int(ts.duplicated().sum())})
            for v in VARS:
                r[f"missing_{v}"] = int(df[v].isna().sum())
                lo, hi = config.LIMITS[v]
                r[f"out_of_range_{v}"] = int((df[v].notna() & ~df[v].between(lo, hi)).sum())
                r[f"range_{v}"] = f"{df[v].min():.1f}..{df[v].max():.1f}"
        else:
            r["failed_checks"] = [c["check"] for c in bf.checks if not c["passed"]]
        rows.append(r)

    L = ["# Member 1: Bronze missing-data report", "",
         "*Generated by `scripts/check_missing_data.py` (`make -C src reports`). Every Bronze file is checked: "
         "Quality Gate 1, hourly timestamp gaps and duplicates, missing values and physical range of every variable, "
         "and NASA POWER `-999` fill values.*", "",
         "| File | Source | Gate 1 | Period (UTC) | Hours | Missing hours | Dup. | Missing T / RH / Td / wind | "
         "Out of range | -999 fills | T range °C | RH range % |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if "timestamps" not in r:
            L.append(f"| {r['file']} | {r['source']} | **FAIL** {r.get('failed_checks')} | | | | | | | | | |")
            continue
        miss = " / ".join(str(r[f"missing_{v}"]) for v in VARS)
        oor = sum(r[f"out_of_range_{v}"] for v in VARS)
        L.append(f"| {r['file']} | {r['source']} | {r['gate1']} | {r['first_utc']} → {r['last_utc']} | {r['timestamps']} | "
                 f"{r['missing_hours_in_range']} | {r['duplicate_timestamps']} | {miss} | {oor} | {r['fill_values_-999']} | "
                 f"{r['range_temperature_c']} | {r['range_humidity_pct']} |")
    total_missing = sum(r.get(f"missing_{v}", 0) for r in rows for v in VARS)
    L += ["", f"**Summary:** {len(rows)} files, {sum(r['gate1'] == 'pass' for r in rows)} passed Gate 1, "
          f"{total_missing} missing variable values, {sum(r['fill_values_-999'] for r in rows)} NASA POWER fill values.",
          "", "Open-Meteo forecast files contain `past_days=14` of recent hours; overlaps between files are resolved "
          "by the pipeline (archive first, otherwise the newest issue).", ""]
    return "\n".join(L), rows


if __name__ == "__main__":
    md, rows = bronze_inspection()
    REPORT.write_text(md, encoding="utf-8")
    summary = next((line for line in md.splitlines() if line.startswith("**Summary:**")), "")
    print(summary.replace("**", ""))
    print("wrote", REPORT.relative_to(ROOT).as_posix())
