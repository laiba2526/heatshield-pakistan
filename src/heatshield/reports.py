"""Generate ``reports/data_quality_report.md``: coverage, missingness, value
ranges per source and city, quality-gate results, Data Quality Agent actions,
quarantine and cross-source agreement for the trusted run.

The Bronze missing-data report is Member 1's ``scripts/check_missing_data.py``.

Usage: ``python -m heatshield.reports`` (part of ``make -C src reports``)
"""
from __future__ import annotations

import json
import sys

import pandas as pd

from heatshield import config, pipeline


def data_quality_report() -> str:
    status = pipeline.read_status()
    vdir = config.REPORTS / "validation"
    run_id = status.get("last_success_run_id")
    rep = json.loads((vdir / f"validation_{run_id}.json").read_text(encoding="utf-8")) if run_id and \
        (vdir / f"validation_{run_id}.json").exists() else {}
    S = config.SILVER
    hourly = pd.read_parquet(S / "weather_hourly.parquet")
    daily = pd.read_csv(config.GOLD / "heat_daily.csv", parse_dates=["date"])
    L = ["# Data quality report — HeatShield Pakistan", "",
         f"*Generated by `make -C src reports` for the trusted run **{run_id}** (finished {status.get('last_success_utc')}).*", "",
         "## 1. Sources", "",
         "| Layer | Source | Role | Variables |", "|---|---|---|---|",
         "| Bronze | Open-Meteo historical archive (2021-10-01 → 2026-10-10) | primary hourly series | T, RH, Td, wind |",
         "| Bronze | Open-Meteo forecast API (`past_days=14`, 4-day forecast), fetched hourly | recent hours + forecast | T, RH, Td, wind |",
         "| Bronze | Copernicus ERA5 via Open-Meteo (`models=era5`) | independent reanalysis cross-check | T, RH, Td, wind |",
         "| Bronze | NASA POWER hourly (MERRA-2 based), 2021–2025 | cross-check + gap filling (≤ 24 h) | T, RH, Td, wind |",
         "| Bronze | NDMA / PDMA Sindh / PMD PDFs | RAG evidence only (never model input) | text |", "",
         "Units are standardised to °C, %, m/s (Open-Meteo wind arrives in km/h and is converted). "
         "All timestamps are UTC; daily aggregates use the local Pakistan day (PKT, UTC+5).", "",
         "## 2. Silver completeness per city", "", "| City | Hours | First (UTC) | Last (UTC) | Valid T+RH | ok | fixed | interpolated | NASA-filled | missing |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for city, g in hourly.groupby("city"):
        vc = g["qc_flag"].value_counts()
        valid = (g["temperature_c"].notna() & g["humidity_pct"].notna()).mean()
        L.append(f"| {city.title()} | {len(g)} | {g['timestamp_utc'].min():%Y-%m-%d %H:%M} | {g['timestamp_utc'].max():%Y-%m-%d %H:%M} | "
                 f"{valid:.2%} | {vc.get('ok', 0)} | {vc.get('fixed', 0)} | {vc.get('filled_interp', 0)} | "
                 f"{vc.get('filled_nasa', 0)} | {vc.get('missing', 0)} |")
    L += ["", "## 3. Quality gates (trusted run)", ""]
    for gate, title in (("gate1", "Gate 1 — Bronze files"), ("gate2", "Gate 2 — publish")):
        g = rep.get(gate)
        if not g:
            continue
        L += [f"**{title}: {'PASS' if g['passed'] else 'FAIL'}**", "", "| Check | Result | Detail |", "|---|---|---|"]
        for c in g["checks"]:
            L.append(f"| {c['check']} | {'pass' if c['passed'] else c['severity'].upper()} | {c.get('detail', '')} |")
        L.append("")
    L += ["## 4. Data Quality Agent actions (trusted run)", "", "| Rule | Records |", "|---|---|"]
    for k, v in rep.get("agent_actions", {}).items():
        L.append(f"| {k} | {v} |")
    L += ["", "`overlap_resolved` counts hours present in several Bronze files (archive vs. successive forecast issues) "
          "— resolved by priority, not a defect. `cross_source` counts local days whose Tmax differs from NASA POWER by "
          f"more than {config.CROSS_SOURCE_TMAX_TOL_C} °C (flagged, not changed).", ""]
    agr = config.GOLD / "source_agreement.csv"
    if agr.exists():
        a = pd.read_csv(agr)
        L += ["## 5. Cross-source agreement (daily Tmax, primary minus reference)", "",
              "| Reference | City | Days | Bias °C | MAE °C | Correlation |", "|---|---|---|---|---|---|"]
        for _, r in a.iterrows():
            L.append(f"| {r['reference']} | {r['city'].title()} | {r['days']} | {r['tmax_bias_c']:+.2f} | {r['tmax_mae_c']:.2f} | {r['tmax_corr']:.3f} |")
        L += ["", "Independence: Open-Meteo's default historical series blends ERA5 / ERA5-Land / ECMWF IFS, so ERA5 "
              "agreement is partly shared heritage; NASA POWER (MERRA-2) is the more independent check.", ""]
    L += ["## 6. Gold layer", "", "| City | Days | Complete days | Days with filled hours | Max heat index °C | Danger+ days |",
          "|---|---|---|---|---|---|"]
    for city, g in daily.groupby("city"):
        L.append(f"| {city.title()} | {len(g)} | {int(g['complete_day'].sum())} | {int((g['filled_hours'] > 0).sum())} | "
                 f"{g['hi_max_c'].max():.1f} | {int((g['hi_max_c'] >= 39.4).sum())} |")
    qdirs = sorted(config.QUARANTINE.glob("*/quarantined_records.csv")) if config.QUARANTINE.exists() else []
    L += ["", "## 7. Quarantine and audit trail", "",
          f"* Quarantined records are kept per run in `data/quarantine/<run_id>/` ({len(qdirs)} run(s) with quarantined data so far, "
          "including fault drills).",
          "* Every run, gate decision and agent action is appended to `data/audit/audit_log.jsonl`; run outcomes to "
          "`data/status/run_history.jsonl`; full per-run validation reports to `reports/validation/`.",
          "* A run that fails a gate never replaces `data/silver` / `data/gold`; its candidate output stays in "
          "`data/_staging/<run_id>` for inspection.", "",
          "## 8. Known limitations", "",
          "* All sources are gridded model/reanalysis products, not station observations.",
          "* NASA POWER covers 2021–2025 only, so 2026 days have ERA5 but no NASA cross-check.",
          "* Three SOP pages (posters) and the Urdu page of the PMD alert have no usable text layer and are excluded from RAG.", ""]
    return "\n".join(L)


def main() -> int:
    config.REPORTS.mkdir(parents=True, exist_ok=True)
    (config.REPORTS / "data_quality_report.md").write_text(data_quality_report(), encoding="utf-8")
    print("wrote reports/data_quality_report.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
